<?php

namespace App\Payments;

/**
 * ถามเกตเวย์ถี่แค่ไหน — ตัวเลขล้วน ทดสอบได้โดยไม่ต้องมีฐานข้อมูล
 *
 * ── ปัญหาที่แก้ ─────────────────────────────────────────────────────────
 * ทั้ง Stripe และ Beam แนะนำ webhook และไม่แนะนำให้วน cron ถาม
 * Beam มีกันสแปม ถามถี่เกินจะได้ HTTP 429 กลับมา
 *
 * แต่เซิร์ฟเวอร์อยู่บนเครื่องในร้าน webhook ยิงเข้ามาไม่ได้ (ดู payment-gateway-design.md)
 * ทางออกคือ **ถามไม่เท่ากันตลอดอายุของรายการ** ไม่ใช่ถามทุกนาทีทุกใบ
 *
 * ── เพดานความถี่ที่แท้จริงคือตัวตั้งเวลา ไม่ใช่ตารางนี้ ──────────────────
 * `pos:poll-charges` ถูกเรียกนาทีละครั้ง ตารางนี้จึงเร็วกว่า 60 วินาทีไม่ได้
 * ตัวเลขต่ำกว่า 60 จะไม่มีความหมาย — จึงไม่ใส่ไว้ให้เข้าใจผิดว่าระบบตอบเร็วกว่านั้น
 *
 * **ทางเร็วสำหรับลูกค้าที่ยืนอยู่หน้าเคาน์เตอร์คือหน้าจอ ไม่ใช่ตัวตั้งเวลา**
 * หน้าที่โชว์ QR อยู่จะเรียกถามใบนั้นใบเดียวตามจังหวะของมันเอง (แบบเดียวกับ
 * ตะกร้าร่วมที่ใช้ usePolling) ตัวตั้งเวลาเป็นตัวกันเหนียวของใบที่ไม่มีใครเฝ้าดู
 * — ยังไม่ได้ต่อ ดู payment-gateway-design.md หัวข้อ "ที่ยังไม่ทำ"
 *
 * ── เหตุผลของช่วงเวลา ───────────────────────────────────────────────────
 * สามนาทีแรกลูกค้ายังอยู่แถวนั้น ถามทุกรอบ
 * พ้นไปแล้วเขาคงเดินไปแล้วหรือเปลี่ยนใจ — ถามห่างลง
 *
 * ── ที่ประหยัดจริงคือเจ้าที่ QR อายุยาว ─────────────────────────────────
 * Beam Bolt บังคับอายุสูงสุด 10 นาที — ตารางนี้ถาม 7 ครั้ง ถามทุกนาทีคือ 10 ครั้ง
 * Stripe อายุ 24 ชม. — ตารางนี้ถามประมาณ 290 ครั้ง ถามทุกนาทีคือ 1,440 ครั้ง
 *
 * และใบที่หมดอายุแล้วถูกปิดที่ฝั่งเราโดยไม่ถามเลยสักครั้ง
 * (ดู PaymentChargeService::pollOpen)
 */
final class PollSchedule
{
    /**
     * ตารางถาม: [อายุของรายการถึงกี่วินาที => ถามห่างกันกี่วินาที]
     *
     * เรียงจากช่วงต้นไปช่วงท้าย ตัวสุดท้ายเป็นค่าของทุกช่วงที่เหลือ
     */
    protected const STEPS = [
        180 => 60,      // สามนาทีแรก — ถามทุกรอบของตัวตั้งเวลา (เร็วสุดที่ทำได้)
        600 => 120,     // ถึงสิบนาที — ครอบอายุสูงสุดของ Beam Bolt
        null => 300,    // หลังจากนั้น — เจ้าที่ QR อายุยาว (Stripe 24 ชม.)
    ];

    /**
     * พื้นล่างของการถามเกตเวย์ "จากหน้าจอ"
     *
     * ── ทำไมต้องมีตัวเลขคนละตัวกับตารางข้างบน ──────────────────────────
     * ตารางข้างบนเป็นจังหวะของ **ตัวตั้งเวลา** ซึ่งเร็วกว่า 60 วินาทีไม่ได้
     * แต่ตอนลูกค้ายืนสแกนอยู่ตรงหน้า การรอถึงหนึ่งนาทีนานเกินไป —
     * หน้าจอที่โชว์ QR อยู่จึงถามถี่กว่านั้นได้
     *
     * ── แล้วทำไมไม่ปล่อยให้หน้าจอถามเร็วเท่าที่อยาก ───────────────────
     * เพราะเบราว์เซอร์เป็นคนกำหนดจังหวะ ไม่ใช่เรา หน้าจอที่ถามทุก 2 วินาที
     * (หรือเปิดค้างไว้สิบจอ) จะยิงเกตเวย์จนได้ HTTP 429 กลับมา แล้ว
     * **ทุกบิลในร้านจะตรวจเงินไม่ได้พร้อมกัน** เพราะโดนกันทั้งร้าน
     *
     * ตัวนี้จึงตัดขาดสองเรื่องออกจากกัน: หน้าจอถามเราถี่แค่ไหนก็ได้
     * แต่ **เราถามเกตเวย์ไม่เกินนาทีละ 12 ครั้งต่อหนึ่งใบ** เสมอ
     * คำขอที่เร็วกว่านั้นได้สถานะล่าสุดจากฐานข้อมูลไปแทน ซึ่งเป็นคำตอบที่ถูกอยู่แล้ว
     */
    public const SCREEN_FLOOR_SECONDS = 5;

    /**
     * ถึงเวลาถามเกตเวย์ให้หน้าจอที่กำลังโชว์ QR อยู่หรือยัง
     *
     * @param  int|null  $sinceLastPoll  ถามครั้งล่าสุดไปกี่วินาทีแล้ว (null = ยังไม่เคยถาม)
     */
    public static function isDueForScreen(?int $sinceLastPoll): bool
    {
        if ($sinceLastPoll === null) {
            return true;
        }

        return $sinceLastPoll >= self::SCREEN_FLOOR_SECONDS;
    }

    /** ถามห่างกันกี่วินาที เมื่อรายการนี้อายุ $ageSeconds แล้ว */
    public static function intervalFor(int $ageSeconds): int
    {
        $ageSeconds = max(0, $ageSeconds);

        foreach (self::STEPS as $upTo => $interval) {
            if ($upTo === null || $ageSeconds < $upTo) {
                return $interval;
            }
        }

        // ไปไม่ถึงตรงนี้ เพราะ STEPS มี null เป็นตัวสุดท้ายเสมอ
        return 300;
    }

    /**
     * ถึงเวลาถามรายการนี้แล้วหรือยัง
     *
     * @param  int  $ageSeconds  รายการนี้ถูกสร้างมากี่วินาทีแล้ว
     * @param  int|null  $sinceLastPoll  ถามครั้งล่าสุดไปกี่วินาทีแล้ว (null = ยังไม่เคยถาม)
     */
    public static function isDue(int $ageSeconds, ?int $sinceLastPoll): bool
    {
        // ยังไม่เคยถาม = ถามเลย ไม่ต้องรอ
        if ($sinceLastPoll === null) {
            return true;
        }

        return $sinceLastPoll >= self::intervalFor($ageSeconds);
    }
}
