<?php

namespace App\Enums;

/**
 * งานที่คิวฝั่งเบราว์เซอร์เก็บไว้ส่งทีหลังได้
 *
 * ── ทำไมมีแค่สามอย่าง ────────────────────────────────────────────────────
 * เฟส 2 เอาแค่ "เพิ่มรายการ + ส่งครัว ในบิลที่เปิดอยู่แล้ว" เพราะสองอย่างนี้
 * ทำงานได้โดยไม่ต้องรู้อะไรจากเซิร์ฟเวอร์เลย บิลมี id จริงอยู่แล้ว
 *
 * เฟส 3 เพิ่ม "รับเงินสด" เข้ามา — ต่างจากสองตัวแรกตรงที่ **มันแทนเงินจริงในลิ้นชัก**
 * ถ้าใบนี้หายไป เงินก้อนนั้นจะไม่มีอะไรอธิบายมัน จึงมีกติกาพิเศษของตัวเองหลายข้อ
 * (ดู OfflineSyncService::payCash และสถานะ held)
 *
 * ที่ *ไม่* อยู่ในนี้และเหตุผล:
 * · เปิดบิลใหม่ — ต้องได้เลขบิลจากเซิร์ฟเวอร์ และต้องกันสองเครื่องเปิดโต๊ะเดียวกัน
 * · แก้จำนวน/ลบรายการที่ขึ้นระบบไปแล้ว — ต้องใช้ id ของรายการ ซึ่งอาจถูกคนอื่นแก้ไปแล้ว
 *   ระหว่างที่เครื่องนี้หลุด การ replay ทับจะกลายเป็นการย้อนงานของคนอื่น
 * · รับเงินด้วยวิธีอื่นนอกจากเงินสด — โอน/พร้อมเพย์ต้องเห็นสลิปจริง บัตรต้องรูด EDC
 *   ทั้งคู่มีหลักฐานอยู่ที่อื่นอยู่แล้ว การให้คีย์ตอนหลุดคือการเปิดช่องให้บันทึกเงินที่ไม่มีจริง
 *
 * (รายการที่ยังไม่ขึ้นระบบ แก้จำนวนหรือลบได้ตามปกติ เพราะมันอยู่แค่ในเครื่อง
 *  ไม่ต้องผ่านคิวนี้ ดู useOfflineQueue.ts ฝั่งหน้าจอ)
 */
enum OfflineEntryKind: string
{
    case AddItem = 'add_item';
    case SendKitchen = 'send_kitchen';
    case PayCash = 'pay_cash';

    public function label(): string
    {
        return match ($this) {
            self::AddItem => 'เพิ่มรายการ',
            self::SendKitchen => 'ส่งครัว',
            self::PayCash => 'รับเงินสด',
        };
    }

    /**
     * ใบนี้แทนเงินจริงหรือเปล่า
     *
     * ใบที่แทนเงินล้มแล้วทิ้งไม่ได้ ต้องกลายเป็นงานของผู้จัดการ (สถานะ held)
     * ส่วนใบที่ไม่ได้แทนเงิน ล้มแล้วให้พนักงานคีย์ใหม่ได้เลย
     */
    public function movesMoney(): bool
    {
        return $this === self::PayCash;
    }
}
