<?php

namespace App\Enums;

use App\Models\Order;
use App\Support\Money;

/**
 * ฐานที่รหัสส่วนลด (voucher) ใช้คิด — ทั้งขั้นต่ำและมูลค่าที่ลดได้
 *
 * ── ทำไมต้องเลือกได้ ────────────────────────────────────────────────
 * ร้านใช้คูปองสองแบบซึ่งขัดกันเองถ้าใช้กติกาเดียว
 *
 *   แบบการตลาด  "ซื้อครบ 400 ลด 10%" — ขั้นต่ำหมายถึงยอดค่าอาหารที่สั่ง
 *               ลูกค้าที่ได้โปรลดไปแล้วก็ยังสั่งครบ 400 อยู่ดี จึงควรใช้ได้
 *
 *   แบบชดเชย    "ขอโทษที่ทำอาหารช้า ใบนี้ลด 100" — ต้องลดจากยอดที่ต้องจ่ายจริง
 *               ถ้าคิดจากยอดค่าอาหาร คูปองจะไปซ้อนกับโปรจนบิลติดลบใกล้ศูนย์
 *
 * กติกานี้เป็นของ "แคมเปญ" ไม่ใช่ของร้าน — คูปองสองใบในร้านเดียวกันตั้งต่างกันได้
 * จึงเก็บที่ตัวคูปอง ไม่ใช่ที่ตั้งค่าสาขา
 *
 * ── ค่าเริ่มต้นคือ MenuTotal โดยตั้งใจ ───────────────────────────────
 * เป็นพฤติกรรมเดิมของระบบ คูปองที่แจกออกไปแล้วต้องใช้ได้เหมือนเดิม
 * การเปลี่ยนความหมายของคูปองที่อยู่ในมือลูกค้าแล้วคือการผิดสัญญากับลูกค้า
 */
enum VoucherBase: string
{
    /** ยอดค่าอาหารที่สั่ง — ก่อนหักโปรโมชั่นและสิทธิ์พนักงาน (พฤติกรรมเดิม) */
    case MenuTotal = 'menu_total';

    /** ยอดที่ลูกค้าต้องจ่ายจริง — หลังหักโปรโมชั่นและสิทธิ์พนักงานแล้ว */
    case AmountDue = 'amount_due';

    public function label(): string
    {
        return match ($this) {
            self::MenuTotal => 'ยอดค่าอาหารที่สั่ง',
            self::AmountDue => 'ยอดที่ต้องจ่ายจริง',
        };
    }

    /** คำอธิบายใต้ตัวเลือก — ต้องอ่านแล้วเลือกถูกโดยไม่ต้องถามใคร */
    public function hint(): string
    {
        return match ($this) {
            self::MenuTotal => 'ใช้ซ้อนกับโปรโมชั่นได้ เหมาะกับคูปองการตลาด "ซื้อครบ X ลด Y"',
            self::AmountDue => 'ลดจากยอดสุทธิหลังหักโปรแล้ว เหมาะกับคูปองชดเชยลูกค้า',
        };
    }

    /**
     * ยอดที่คูปองใบนี้มองเห็น
     *
     * ── สองตัวที่หักออกทุกกรณี ─────────────────────────────────────
     * `item_discount` กับ `bill_discount` คือส่วนลดที่ "พนักงานกดเอง"
     * ไม่ใช่โปรที่ระบบใส่ให้ การหักมันออกก่อนจึงไม่ใช่การกันโปรซ้อน
     * แต่เป็นการไม่ให้คูปองคิดจากเงินที่ร้านลดให้ไปแล้วด้วยมือ
     *
     * ── ตัวที่ไม่หักออกไม่ว่ากรณีใด ────────────────────────────────
     * `voucher_discount` — เพราะนั่นคือสิ่งที่กำลังคำนวณอยู่
     * ถ้าหักออก การคิดคูปองซ้ำรอบสองจะได้ยอดน้อยลงเรื่อย ๆ ทุกครั้งที่ลองใส่รหัส
     */
    public function baseFor(Order $order): float
    {
        $base = (float) $order->subtotal
            - (float) $order->item_discount
            - (float) $order->bill_discount;

        if ($this === self::AmountDue) {
            $base -= (float) $order->promotion_discount + (float) $order->staff_discount;
        }

        return max(0.0, Money::round($base));
    }

    /** @return array<int, array{value: string, label: string, hint: string}> */
    public static function options(): array
    {
        return array_map(
            fn (self $c) => ['value' => $c->value, 'label' => $c->label(), 'hint' => $c->hint()],
            self::cases(),
        );
    }
}
