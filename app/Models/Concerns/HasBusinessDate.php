<?php

namespace App\Models\Concerns;

use Illuminate\Support\Carbon;

/**
 * เก็บ business_date ลงฐานข้อมูลเป็น "วันที่" ไม่ใช่ "วันที่พร้อมเวลา"
 *
 * ── บั๊กที่แก้ ───────────────────────────────────────────────────────────
 * คอลัมน์ `business_date` ประกาศเป็น `date` และทุกคิวรีในระบบเทียบกับ `Y-m-d`
 * แต่ cast `'business_date' => 'date'` ของ Eloquent เขียนค่าลงฐานข้อมูลผ่าน
 * `fromDateTime()` ซึ่งใช้ `$dateFormat` ของ model = **`Y-m-d H:i:s`**
 * ค่าที่ถูกเก็บจริงจึงเป็น `2026-09-25 00:00:00` ไม่ใช่ `2026-09-25`
 *
 * SQL Server กลืนความต่างนี้ให้ เพราะคอลัมน์เป็นชนิด `date` จริง
 * มันแปลงสตริงที่มีเวลาต่อท้ายให้เป็นวันที่ตอน insert แล้วการเทียบก็ตรง
 *
 * sqlite (ที่เทสต์ใช้) ไม่มีชนิดวันที่ — ชนิด `date` ได้ NUMERIC affinity
 * ซึ่งเก็บสตริงนั้นไว้เป็น text ตามตัวอักษร ผลคือ:
 *
 *   WHERE business_date = '2026-09-25'                 → 0 แถว
 *   whereBetween('business_date', [..., '2026-09-25'])  → **วันสุดท้ายหายไป**
 *   firstOrNew(['business_date' => '2026-09-25'])       → หาไม่เจอ แล้วชน unique
 *
 * ── ทำไมเรื่องนี้ร้ายกว่าที่เห็น ─────────────────────────────────────────
 * บนเครื่องจริงมันทำงานถูก แต่ในเทสต์มันเงียบ เทสต์ที่ถามว่า "วันนี้ขายได้เท่าไหร่"
 * จะได้ 0 แล้วถ้าเผลอเขียน assert ไว้ว่า 0 มันก็ **ผ่าน** ทั้งที่คิวรีพัง
 * ทั้งรายงาน · ใบนำส่งเงิน · การกระทบยอดธนาคาร · การส่งออกยอดขาย
 * จึงกลายเป็นพื้นที่ที่เทสต์คุมไม่ได้เลย ทั้งที่มีเทสต์อยู่
 *
 * ── ทำไมแก้ด้วย mutator ไม่ใช่เปลี่ยน cast หรือเปลี่ยนคิวรีเป็น whereDate ──
 * `setAttribute()` ของ Eloquent เรียก mutator **ก่อน** `fromDateTime()` และคืนค่าทันที
 * จึงคุมรูปแบบตอนเขียนได้จุดเดียว โดย:
 *
 *   • cast `'date'` ยังอยู่ → อ่านออกมาเป็น Carbon เหมือนเดิม
 *     และ `toArray()` / JSON ที่ส่งไปหน้าจอยังเป็นรูปเดิมเป๊ะ (ไม่กระทบ Vue)
 *   • คิวรีทุกที่ไม่ต้องแก้ → index บนคอลัมน์วันที่ยังถูกใช้
 *     (`whereDate` จะห่อคอลัมน์ด้วยฟังก์ชัน ซึ่งทำให้ index ใช้ไม่ได้ และมี 29 จุดที่ต้องแก้ให้ครบ)
 *   • ข้อมูลเดิมบน SQL Server เป็นวันที่อยู่แล้ว → ไม่ต้อง migrate
 *
 * พูดอีกอย่าง: คอมเมนต์ที่เขียนไว้ใน `CashSettlementService::shiftsOf()` ว่า
 * "ใช้ where ไม่ใช่ whereDate เพราะ business_date เป็นคอลัมน์ DATE อยู่แล้ว"
 * นั้นถูก — สิ่งที่ผิดคือฝั่งเขียนที่ไม่ได้เก็บเป็น DATE จริง ตัวนี้แก้ตรงนั้น
 */
trait HasBusinessDate
{
    public function setBusinessDateAttribute(mixed $value): void
    {
        $this->attributes['business_date'] = $value === null || $value === ''
            ? null
            : Carbon::parse($value)->format('Y-m-d');
    }
}
